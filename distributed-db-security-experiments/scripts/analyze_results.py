def fmt(value) -> str:
    try:
        if pd.isna(value):
            return "-"
        return f"{float(value):.2f}"
    except Exception:
        return str(value)


def render_shard_load_figure(df: pd.DataFrame, output: Path) -> None:
    hot = df[(df["scenario"] == "hot90") & (df["success"] == True)].copy()  # noqa: E712
    hot = hot[hot["physical_shard"].astype(str).str.startswith("shard-")]
    pivot = (
        hot.groupby(["defense", "physical_shard"])
        .size()
        .unstack(fill_value=0)
        .reindex(index=["baseline", "shard_limit", "hot_key_limit", "queue_isolation"])
    )
    for shard in ["shard-0", "shard-1", "shard-2"]:
        if shard not in pivot.columns:
            pivot[shard] = 0
    pivot = pivot[["shard-0", "shard-1", "shard-2"]]

    plt.figure(figsize=(9.5, 5.2))
    x = range(len(pivot.index))
    width = 0.24
    colors = ["#C94C4C", "#4C78A8", "#59A14F"]
    for idx, shard in enumerate(pivot.columns):
        plt.bar(
            [pos + (idx - 1) * width for pos in x],
            pivot[shard].values,
            width=width,
            label=shard,
            color=colors[idx],
        )
    plt.xticks(list(x), [DEFENSE_LABELS_EN.get(item, item) for item in pivot.index], rotation=8)
    plt.ylabel("Successful DB requests")
    plt.xlabel("Defense strategy")
    plt.title("Physical shard load under 90% hotspot traffic")
    plt.legend()
    plt.tight_layout()
    plt.savefig(output, dpi=180)
    plt.close()


def render_tidb_tikv_figure(df: pd.DataFrame, output: Path) -> None:
    if df.empty:
        return
    pivot = (
        df.groupby(["scenario", "container"])["cpu_percent"]
        .max()
        .unstack(fill_value=0)
        .reindex(index=["tidb_uniform", "tidb_hot70", "tidb_hot90"])
    )
    plt.figure(figsize=(9.5, 5.2))
    x = range(len(pivot.index))
    width = 0.24
    colors = ["#4C78A8", "#59A14F", "#F28E2B"]
    for idx, container in enumerate(pivot.columns):
        plt.bar(
            [pos + (idx - 1) * width for pos in x],
            pivot[container].values,
            width=width,
            label=container.replace("exp1_tidb_", ""),
            color=colors[idx % len(colors)],
        )
    plt.xticks(list(x), ["uniform", "70% hotspot", "90% hotspot"])
    plt.ylabel("Peak CPU (%)")
    plt.xlabel("Traffic scenario")
    plt.title("TiKV load under TiDB hotspot traffic")
    plt.legend()
    plt.tight_layout()
    plt.savefig(output, dpi=180)
    plt.close()


