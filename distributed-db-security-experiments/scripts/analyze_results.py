#!/usr/bin/env python3
"""Analyze distributed database security experiment results."""

from __future__ import annotations

import argparse
import math
from pathlib import Path
from typing import Dict, List

import matplotlib.pyplot as plt
import pandas as pd


DEFENSE_LABELS = {
    "baseline": "Baseline",
    "shard_limit": "分片级限流",
    "hot_key_limit": "热点 key 限流",
    "queue_isolation": "队列隔离/读分流",
}

SCENARIO_LABELS = {
    "uniform": "均匀流量",
    "hot70": "70% 热点流量",
    "hot90": "90% 热点流量",
}


def main() -> int:
    args = parse_args()
    root = Path(__file__).resolve().parents[1]
    raw_path = root / args.requests_csv
    table_dir = root / "results" / "tables"
    figure_dir = root / "results" / "figures"
    paper_dir = root / "paper"
    table_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)
    paper_dir.mkdir(parents=True, exist_ok=True)

    requests = pd.read_csv(raw_path)
    summary = summarize_requests(requests)
    summary_path = table_dir / "exp1_single_shard_flood_summary.csv"
    summary.to_csv(summary_path, index=False)

    table_md = render_table_a(summary)
    table_path = table_dir / "table_A_single_shard_flood.md"
    table_path.write_text(table_md, encoding="utf-8")

    figure_path = figure_dir / "exp1_shard_load_changes.png"
    render_shard_load_figure(requests, figure_path)

    paper_path = paper_dir / "section_4_append_text.md"
    paper_path.write_text(render_paper_text(summary), encoding="utf-8")

    print(f"[analyze] wrote {summary_path}")
    print(f"[analyze] wrote {table_path}")
    print(f"[analyze] wrote {figure_path}")
    print(f"[analyze] wrote {paper_path}")
    return 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--requests-csv",
        default="results/raw/exp1_single_shard_flood_requests.csv",
        help="request-level raw CSV generated by exp1_single_shard_flood.py",
    )
    return parser.parse_args()


def summarize_requests(df: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []
    for (scenario, defense), group in df.groupby(["scenario", "defense"], sort=False):
        duration = max(group["end_ts"].max() - group["start_ts"].min(), 0.001)
        success = group[group["success"] == True]  # noqa: E712
        limited = group[group["error"].isin(["shard_limit", "hot_key_limit", "hot_queue_full"])]
        timeout = group[group["error"].astype(str).str.contains("timeout", na=False)]
        latencies = group["latency_ms"].astype(float)
        physical_counts = (
            success[success["physical_shard"].astype(str).str.startswith("shard-")]
            .groupby("physical_shard")
            .size()
            .to_dict()
        )
        hot_load = float(physical_counts.get("shard-0", 0))
        cold_loads = [float(physical_counts.get(f"shard-{i}", 0)) for i in (1, 2)]
        cold_mean = max(sum(cold_loads) / len(cold_loads), 1.0)
        rows.append(
            {
                "scenario": scenario,
                "defense": defense,
                "requests": int(len(group)),
                "success_rate_pct": pct(len(success), len(group)),
                "failure_rate_pct": pct(len(group) - len(success), len(group)),
                "rate_limited_pct": pct(len(limited), len(group)),
                "timeout_pct": pct(len(timeout), len(group)),
                "qps": len(group) / duration,
                "avg_latency_ms": latencies.mean(),
                "p95_latency_ms": latencies.quantile(0.95),
                "p99_latency_ms": latencies.quantile(0.99),
                "physical_shard0_requests": int(hot_load),
                "physical_shard1_requests": int(physical_counts.get("shard-1", 0)),
                "physical_shard2_requests": int(physical_counts.get("shard-2", 0)),
                "cache_hits": int((group["physical_shard"] == "cache").sum()),
                "hot_physical_load_ratio": hot_load / cold_mean,
            }
        )

    summary = pd.DataFrame(rows)
    summary["uniform_qps_overhead_pct"] = math.nan
    summary["uniform_p95_overhead_pct"] = math.nan
    uniform = summary[summary["scenario"] == "uniform"].set_index("defense")
    if "baseline" in uniform.index:
        base_qps = float(uniform.loc["baseline", "qps"])
        base_p95 = float(uniform.loc["baseline", "p95_latency_ms"])
        mask = summary["scenario"] == "uniform"
        summary.loc[mask, "uniform_qps_overhead_pct"] = (
            (summary.loc[mask, "qps"] - base_qps) / base_qps * 100.0
        )
        summary.loc[mask, "uniform_p95_overhead_pct"] = (
            (summary.loc[mask, "p95_latency_ms"] - base_p95) / base_p95 * 100.0
        )
    return summary


def pct(part: int, total: int) -> float:
    if total == 0:
        return 0.0
    return part / total * 100.0


def render_table_a(summary: pd.DataFrame) -> str:
    cols = [
        "场景",
        "防御策略",
        "成功率(%)",
        "限流率(%)",
        "QPS",
        "平均延迟(ms)",
        "P95(ms)",
        "P99(ms)",
        "热点物理负载比",
        "均匀流量QPS变化(%)",
    ]
    lines = ["# 表A：单分片泛洪攻击与防御效果", "", "|" + "|".join(cols) + "|"]
    lines.append("|" + "|".join(["---"] * len(cols)) + "|")
    for _, row in summary.iterrows():
        lines.append(
            "|"
            + "|".join(
                [
                    SCENARIO_LABELS.get(row["scenario"], row["scenario"]),
                    DEFENSE_LABELS.get(row["defense"], row["defense"]),
                    fmt(row["success_rate_pct"]),
                    fmt(row["rate_limited_pct"]),
                    fmt(row["qps"]),
                    fmt(row["avg_latency_ms"]),
                    fmt(row["p95_latency_ms"]),
                    fmt(row["p99_latency_ms"]),
                    fmt(row["hot_physical_load_ratio"]),
                    fmt(row["uniform_qps_overhead_pct"]),
                ]
            )
            + "|"
        )
    lines.append("")
    lines.append(
        "注：热点物理负载比为 shard-0 的成功数据库请求量与 shard-1/shard-2 平均请求量之比；"
        "队列隔离/读分流组中的缓存命中不计入物理分片请求。"
    )
    return "\n".join(lines)


def fmt(value) -> str:
    try:
        if pd.isna(value):
            return "-"
        return f"{float(value):.2f}"
    except Exception:
        return str(value)


def render_shard_load_figure(df: pd.DataFrame, output: Path) -> None:
    hot = df[(df["scenario"] == "hot90") & (df["success"] == True)].copy()  # noqa: E712
    hot = hot[hot["physical_shard"].astype(str).str.startswith("shard-")]
    pivot = (
        hot.groupby(["defense", "physical_shard"])
        .size()
        .unstack(fill_value=0)
        .reindex(index=["baseline", "shard_limit", "hot_key_limit", "queue_isolation"])
    )
    for shard in ["shard-0", "shard-1", "shard-2"]:
        if shard not in pivot.columns:
            pivot[shard] = 0
    pivot = pivot[["shard-0", "shard-1", "shard-2"]]

    plt.figure(figsize=(9.5, 5.2))
    x = range(len(pivot.index))
    width = 0.24
    colors = ["#C94C4C", "#4C78A8", "#59A14F"]
    for idx, shard in enumerate(pivot.columns):
        plt.bar(
            [pos + (idx - 1) * width for pos in x],
            pivot[shard].values,
            width=width,
            label=shard,
            color=colors[idx],
        )
    plt.xticks(list(x), [DEFENSE_LABELS.get(item, item) for item in pivot.index], rotation=10)
    plt.ylabel("成功数据库请求数")
    plt.xlabel("防御策略")
    plt.title("90% 热点流量下各分片物理负载变化")
    plt.legend()
    plt.tight_layout()
    plt.savefig(output, dpi=180)
    plt.close()


def render_paper_text(summary: pd.DataFrame) -> str:
    lookup = summary.set_index(["scenario", "defense"])

    def v(scenario: str, defense: str, column: str) -> float:
        return float(lookup.loc[(scenario, defense), column])

    base_p99 = v("hot90", "baseline", "p99_latency_ms")
    queue_p99 = v("hot90", "queue_isolation", "p99_latency_ms")
    base_ratio = v("hot90", "baseline", "hot_physical_load_ratio")
    queue_ratio = v("hot90", "queue_isolation", "hot_physical_load_ratio")
    shard_limited = v("hot90", "shard_limit", "rate_limited_pct")
    hotkey_limited = v("hot90", "hot_key_limit", "rate_limited_pct")
    uniform_queue_qps = v("uniform", "queue_isolation", "uniform_qps_overhead_pct")
    uniform_shard_p95 = v("uniform", "shard_limit", "uniform_p95_overhead_pct")

    return f"""# 第4章补充实验：单分片泛洪攻击与防御评估

## 实验动机

第2章将数据分发机制风险列为分布式数据库的重要攻击面。与 SQL 注入不同，单分片泛洪流量通常由合法查询、更新和插入组成，外围 WAF/IDS 很难仅根据语法特征区分其攻击性。为量化该类风险，本文构建 PostgreSQL 三分片环境，使用路由层按 `item_id mod 3` 将请求分发到 shard-0、shard-1 和 shard-2，并比较无防御、分片级限流、热点 key 限流、队列隔离/读分流四类策略。

## 实验设计

实验设置三种流量分布：均匀流量、70% 请求集中到 shard-0 热点 key 范围、90% 请求集中到 shard-0 热点 key 范围。每组请求采用 70% `SELECT`、20% `UPDATE`、10% `INSERT` 的读写混合负载。所有请求均为正常 SQL 访问，实验不依赖注入载荷或异常语法。指标包括 QPS、平均延迟、P95/P99 延迟、失败率、限流率、每个分片的物理请求量，以及正常均匀流量下防御策略带来的性能开销。

## 结果与分析

在 90% 热点流量下，无防御组的热点物理负载比达到 {base_ratio:.2f}，P99 延迟为 {base_p99:.2f} ms，说明合法热点请求会将压力集中到单个分片并抬高尾延迟。队列隔离/读分流将热点物理负载比降至 {queue_ratio:.2f}，P99 延迟为 {queue_p99:.2f} ms，表明将热点读流量转移到缓存/副本模拟路径、并对热点写请求使用独立队列，可以降低热点分片对整体处理路径的阻塞。分片级限流和热点 key 限流分别在 90% 热点流量下触发 {shard_limited:.2f}% 和 {hotkey_limited:.2f}% 的限流，通过牺牲部分热点请求的即时成功率换取尾延迟和非热点请求保护。

在正常均匀流量下，队列隔离/读分流的 QPS 变化为 {uniform_queue_qps:.2f}%，分片级限流的 P95 延迟变化为 {uniform_shard_p95:.2f}%。这说明防御机制并非无成本：限流、队列调度和读分流会引入一定调度开销，且在参数设置过紧时可能降低正常请求吞吐。因此，单分片泛洪防御应结合业务容量进行阈值校准，而不能只依赖静态规则。

## 评测边界

需要说明的是，分布式架构级攻击通常与具体系统实现、部署拓扑、共识协议版本及云平台权限模型高度相关。直接复现某一产品级共识漏洞或云基础设施攻击，不仅需要特定历史版本和故障注入条件，也可能引入较高的安全与伦理风险。因此，本实验采用“机制复现”的方式进行评估：使用 PostgreSQL 三分片环境抽象复现单分片泛洪风险，并量化限流、热点 key 隔离和队列化机制的防御代价。该设计并不声称覆盖所有分布式数据库攻击类型，而是用于量化第2章所讨论的数据分发机制风险在受控实验条件下的影响边界和防御代价。
"""


if __name__ == "__main__":
    raise SystemExit(main())
